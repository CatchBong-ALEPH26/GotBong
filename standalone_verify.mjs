import assert from 'node:assert/strict';
import {CONTRADICTIONS, discoverClue, hasDiscoveredClue, publicInvestigation, recordContradictions} from './lib_game_contradictions.mjs';
const fact = (...ids)=>({unlocked:ids, evidence:[]});
let state={A:fact(),B:fact(),C:fact(),D:fact(),investigation:{discoveredClues:[],solvedContradictions:[]}};
let n=0;
const ok=(test)=>{assert.ok(test);n++};
ok(CONTRADICTIONS.length===6);
ok(!hasDiscoveredClue(state,'receiver'));
state=discoverClue(state,'receiver');
ok(hasDiscoveredClue(state,'receiver'));
ok(discoverClue(state,'receiver')===state);
state.D={unlocked:['d_cable_excuse'],evidence:[]};
ok(recordContradictions(state,['d_cable_excuse']).newlySolved.length===0);
state.D.evidence=['cite:a_testimony'];
ok(recordContradictions(state,[]).newlySolved.length===0);
let result=recordContradictions(state,['d_cable_excuse']);
ok(result.newlySolved[0].id==='core_01');
state=result.state;
ok(recordContradictions(state,['d_cable_excuse']).newlySolved.length===0);
state.D.unlocked.push('d_receiver');
state.D.evidence.push('clue:receiver');
ok(recordContradictions(state,['d_receiver']).newlySolved.length===0);
state.D.evidence.push('cite:c_cable');
result=recordContradictions(state,['d_receiver']);
ok(result.newlySolved[0].id==='core_02');
state=result.state;
state.D.unlocked.push('d_delete');
state.D.evidence.push('clue:trash');
ok(recordContradictions(state,['d_delete']).newlySolved.length===0);
state.D.evidence.push('cite:b_typing');
result=recordContradictions(state,['d_delete']);
ok(result.newlySolved[0].id==='core_03');
state=result.state;
state.D.unlocked.push('d_motive');
ok(recordContradictions(state,['d_motive']).newlySolved.length===0);
state.D.evidence.push('clue:chat');
state=recordContradictions(state,['d_motive']).state;
ok(publicInvestigation(state).core===4);
state.B={unlocked:['b_compare'],evidence:['clue:source']};
state.C={unlocked:['c_usb_distinction'],evidence:['clue:c_front_usb','clue:receiver']};
state=recordContradictions(state,['b_compare']).state;
state=recordContradictions(state,['c_usb_distinction']).state;
ok(publicInvestigation(state).optional===2);
ok(!JSON.stringify(publicInvestigation(state)).includes('d_delete'));
console.log(`Standalone contradiction tests: ${n}/${n} pass`);
