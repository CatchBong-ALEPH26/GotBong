//
// 사실(fact) 필드
//   start      게임 시작부터 알고 말할 수 있는 사실
//
//   ── 해금 판정 (docs/game/AI_REDESIGN_DECISIONS.md) ──
//   해금 여부는 빠른 모델이 질문별 기준 점수로 판정하고, 코드는 아래 값으로 합산·비교만 한다.
//   tier       'normal'(합계 3점) | 'important'(4점) | 'core'(S1·S2 모두 2점 + 합계 4점)
//   after      앞 단계 사실 (G1). 모두 풀려 있어야 해금 가능. 코드가 기록과 대조한다
//   elements   S1 채점용 핵심 요소 (누가·무엇을·어디서·언제 중 이 사실이 담은 것)
//   basis      어떤 근거(첨부·지난 대화)에서 이끌어 낸 질문이면 자연스러운지. 판정 모델에 그대로 준다
//   unlock     예전 조건 문법. 이제 해금을 결정하지 않는다. 키 없는 테스트 모드(Fixture)가 모델 판정을
//              흉내 낼 때만 쓴다. 원자: 'cite:<factId>'(다른 사람의 그 발언을 첨부, 누적)
//              'clue:<clueId>'(단서 카드 첨부, 누적) 'ask:<intentId>'(그런 취지로 직접 물음)
//              'has:<factId>'(이미 털어놓은 사실 = after). 조합: { all: [...] } / { any: [...] }
//   revokedBy  이 사실들 중 하나가 해금되면 더는 주장하지 않는 거짓말·숨김(cover)
//   say        말할 내용 (문장은 캐릭터 말투로 새로 만든다)
//   hint       해금 전, 본인이 의식적으로 숨기고 있는 것의 짧은 설명. 없으면 해금 전엔 아예 전달하지 않는다
//   never      어떤 단계에서도 하면 안 되는 말 (역할 단위)
//   intents    (역할 단위) 'ask:' 원자의 설명과 키워드. 이제 테스트 모드(Fixture) 흉내에만 쓴다

