const COUNT_WORD = { 1: '한', 2: '두', 3: '세' };

/** 변형 중 하나를 고른다. seed 는 게임 revision 등 요청마다 달라지는 값 (없으면 무작위). */
export function pickThought(list, seed) {
  const i = Number.isInteger(seed) ? Math.abs(seed) % list.length : Math.floor(Math.random() * list.length);
  return list[i];
}

/** 반려 문구: 4개 이상 / 마지막 하나 / 남은 기회 초과 */
export function rejectThought(reason, remaining, seed) {
  if (reason === 'too_many') return pickThought(thoughts.tooMany, seed);
  if (remaining <= 1) return pickThought(thoughts.lastOne, seed);
  return pickThought(thoughts.overRemaining, seed).replace('{n}', COUNT_WORD[remaining] ?? '세');
}

/** 상황 이름으로 속마음 한 줄 */
export const say = (key, seed) => pickThought(thoughts[key], seed);
